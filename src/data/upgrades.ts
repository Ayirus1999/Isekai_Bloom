export function getUpgrade(id: string): UpgradeDef | undefined {
  return UPGRADES.find((upgrade) => upgrade.id === id);
}

/** Rarity weights shift toward rarer cards as the adventure deepens. */
export function rarityWeights(encounterIndex: number): Record<Rarity, number> {
  const depth = Math.min(1, encounterIndex / 9);
  return {
    common: 46 - depth * 22,
    uncommon: 30 - depth * 6,
    rare: 17 + depth * 12,
    epic: 6 + depth * 12,
    legendary: 1 + depth * 4,
  };
}
